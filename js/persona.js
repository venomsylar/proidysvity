const TRAIT_KEYS = Object.keys(TRAITS);
const traitOf = p => (p && p.type === 'bot' && !p.wasRemote && TRAITS[p.trait]) || null;
// параметр характеру (або значення за замовчуванням)
const TT = (p, k, d = 0) => { const t = traitOf(p); return t && t[k] != null ? t[k] : d; };
const isTrait = (p, k) => !!traitOf(p) && p.trait === k;
function rollTraits(players) {
  const bag = shuffle([...TRAIT_KEYS]);
  players.filter(p => p.type === 'bot').forEach(p => { if (!TRAITS[p.trait]) p.trait = bag.length ? bag.pop() : pick(TRAIT_KEYS); });
}
const traitTag = p => { const t = traitOf(p); return t ? `<span class="trait" title="${esc(t.name)}: ${esc(t.desc)}">${t.icon}</span>` : ''; };

/* --- репліки --- */
// репліка за подією (з шансом і перервою, щоб боти не заговорювали гру)
function botSay(p, ev, vars = {}, chance = .75) {
  const t = traitOf(p); if (!t || G.over && ev !== 'gameWin') return;
  const lines = t.lines[ev]; if (!lines || !lines.length) return;
  botSayText(p, pick(lines).replace(/\{(\w)\}/g, (_, k) => vars[k] != null ? vars[k] : ''), chance);
}
// довільна репліка бота, з тими самими перервами
function botSayText(p, text, chance = .6) {
  const t = traitOf(p); if (!t || !text) return;
  const now = performance.now();
  if (now - (p._sayT || 0) < 5000 / (t.talk || 1) || now - (G._sayT || 0) < 1400) return;
  if (Math.random() > Math.min(1, chance * (t.talk || 1))) return;
  sayLine(p, text);
}
// показати будь-яку репліку над місцем гравця (для господаря — ще й розіслати гостям)
function sayLine(p, text) {
  if (!p || !text) return;
  p._sayT = G._sayT = performance.now();
  if (NET.role === 'host') emitFx('say', { who: p.idx, text });
  speechBubble(p, text);
}
function speechBubble(p, text) {
  if (!p || !p.seat || typeof screenOf !== 'function') return;
  const sp = screenOf(p.seat.anchor.clone().setY(2.3));
  // місце за верхнім краєм екрана — бульбашку опускаємо під верхню панель
  domPop('mbubble say', `<small style="color:${p.color}">${esc(p.name)}</small>${esc(text)}`, clamp(sp.x, 125, innerWidth - 125), Math.max(sp.y, 130), 2900);
}
// бот вирвався вперед і близький до перемоги — похвалитися
function botLeadCheck(p) {
  if (!traitOf(p) || G.coop || G.over) return;
  const others = G.players.filter(q => q !== p && !sameTeam(p, q));
  if (others.length && levelsToWin(p) <= 3 && others.every(q => q.level < p.level)) botSay(p, 'lead', {}, .6);
}
